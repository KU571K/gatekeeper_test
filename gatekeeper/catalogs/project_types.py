"""Семь типов проекта из описания привратника. В раскладе их от 1 до 3.

Коды стабильны для будущего переноса в бэкенд.
Полные определения с примерами лежат в prompts/project_types.md и уходят в модель оттуда.
"""

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class ProjectType:
    code: str
    title: str
    goal: str


PROJECT_TYPES: tuple[ProjectType, ...] = (
    ProjectType(
        'technological',
        'Технологический проект',
        'Разработать, создать или усовершенствовать техническое решение, программный продукт, устройство или систему.',
    ),
    ProjectType(
        'research',
        'Исследовательский проект',
        'Изучить проблему, проверить гипотезу, получить новые знания или экспериментально подтвердить эффективность метода.',
    ),
    ProjectType(
        'creative',
        'Творческий проект',
        'Создать оригинальный творческий продукт или реализовать художественную, культурную или медиаконцепцию.',
    ),
    ProjectType(
        'entrepreneurial',
        'Предпринимательский проект',
        'Разработать, проверить или реализовать бизнес-модель, ориентированную на коммерческую ценность, выручку или прибыль.',
    ),
    ProjectType(
        'social',
        'Социальный проект',
        'Решить общественно значимую проблему, помочь целевой группе или улучшить жизнь людей и сообществ.',
    ),
    ProjectType(
        'external_customer',
        'Проект по запросу внешнего заказчика',
        'Выполнить задачу конкретного внешнего заказчика, который определяет требования к результату.',
    ),
    ProjectType(
        'acceleration',
        'Акселерационный проект',
        'Проверить перспективность идеи и довести проект до измеримых результатов в программе акселерации.',
    ),
)

_BY_CODE = {item.code: item for item in PROJECT_TYPES}


def project_type_by_code(code: str) -> ProjectType | None:
    return _BY_CODE.get(code)
