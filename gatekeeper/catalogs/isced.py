_BY_CODE = {theme.code: theme for theme in THEMES}


def theme_by_code(code: str) -> Theme | None:
    normalized = code.strip()
    if normalized.isdigit():
        normalized = normalized.zfill(2)
    return _BY_CODE.get(normalized)


def render_themes() -> str:
    return '\n'.join(
        f'{theme.code} — {theme.title}. Включать: {theme.includes}' for theme in THEMES
    )
